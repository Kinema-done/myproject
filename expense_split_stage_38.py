def test_edge_cases():
    """Тесты пограничных случаев и ошибок."""

    # Тест 1: Попытка разделить 0 на 0 участников
    assert divide(0, 0) is None, "Деление на ноль должно возвращать None"

    # Тест 2: Деление отрицательного числа на количество участников
    assert divide(-10, 2) == -5.0, "Отрицательное число должно делиться корректно"

    # Тест 3: Деление 0 на положительное количество участников
    assert divide(0, 3) == 0.0, "Ноль должен делиться на любое число"

    # Тест 4: Деление с плавающей точкой
    assert divide(10, 3) == 3.3333333333333335, "Плавающая точка должна обрабатываться корректно"

    # Тест 5: Деление с очень большим числом участников
    assert divide(1000, 100000) == 0.00001, "Очень большое число должно обрабатываться корректно"

    # Тест 6: Деление с очень маленьким числом участников
    assert divide(1000, 1) == 1000.0, "Очень маленькое число должно обрабатываться корректно"

    # Тест 7: Деление с отрицательным количеством участников
    assert divide(10, -2) == -5.0, "Отрицательное число должно делиться корректно"

    # Тест 8: Деление с отрицательным числом и отрицательным количеством участников
    assert divide(-10, -2) == 5.0, "Отрицательное число должно делиться корректно"

    # Тест 9: Деление с нулём и отрицательным количеством участников
    assert divide(0, -3) == 0.0, "Ноль должен делиться на любое число"

    # Тест 10: Деление с плавающей точкой и отрицательным количеством участников
    assert divide(-10.5, -3) == 3.5, "Плавающая точка должна обрабатываться корректно"

    print("Все тесты пройдены!")

test_edge_cases()
